    ('zwillinge', 'Zwillinge', 'case'),
    ('zwillingsbruder', 'Zwillingsbruder', 'case'),
    ('zwillingsschwestern', 'Zwillingsschwestern', 'case'),
    ('zwischen welten', 'Zwischen Welten', 'case'),
    ('zwischenleben', 'Zwischenleben', 'case'),
    ('zwoelf', 'Zwölf', 'umlaut'),
    ('zwoelf maenner jahr', 'Zwölf Männer Jahr', 'umlaut'),
    ('zypern', 'Zypern', 'case'),
    ('zypressen', 'Zypressen', 'case'),
    ('zzz', 'Zzz', 'case');

  IF EXISTS (SELECT 1 FROM title_fix WHERE kind='case' AND lower(old_title) <> lower(new_title)) THEN
    RAISE EXCEPTION 'case-Zeile ändert mehr als die Groß-/Kleinschreibung';
  END IF;

  SELECT count(DISTINCT f.old_title) INTO n_titel
  FROM title_fix f JOIN public.books b ON b.title_display = f.old_title;

  -- nur Groß-/Kleinschreibung: ein Exemplar pro Autor, Trigger zieht die anderen nach
  WITH reps AS (
    SELECT DISTINCT ON (b.author_id, b.title_display) b.id, f.new_title
    FROM public.books b
    JOIN title_fix f ON b.title_display = f.old_title AND f.kind = 'case'
    ORDER BY b.author_id, b.title_display, b.id
  )
  UPDATE public.books b SET title_display = r.new_title
  FROM reps r WHERE b.id = r.id;
  GET DIAGNOSTICS n_case = ROW_COUNT;

  -- Umlaute/ß: alle Exemplare
  UPDATE public.books b SET title_display = f.new_title
  FROM title_fix f
  WHERE b.title_display = f.old_title AND f.kind = 'umlaut';
  GET DIAGNOSTICS n_umlaut = ROW_COUNT;

  ALTER TABLE public.books ENABLE TRIGGER trg_books_set_updated_at;

  -- Kontrolle: keine alte Schreibweise darf übrig sein
  SELECT count(*) INTO n_rest
  FROM title_fix f JOIN public.books b ON b.title_display = f.old_title;
  IF n_rest > 0 THEN
    RAISE EXCEPTION 'ABBRUCH: % Bücher haben noch die alte Schreibweise – nichts gespeichert', n_rest;
  END IF;

  IF testlauf THEN
    RAISE EXCEPTION 'TESTLAUF OK (nichts gespeichert): % Titel gefunden, % Schreibweise-Updates (+ Kopien per Trigger), % Umlaut-Updates. Zum Speichern testlauf := false setzen.',
      n_titel, n_case, n_umlaut;
  END IF;

  RAISE NOTICE 'GESPEICHERT: % Titel, % Schreibweise-Updates (+ Kopien per Trigger), % Umlaut-Updates',
    n_titel, n_case, n_umlaut;
END
